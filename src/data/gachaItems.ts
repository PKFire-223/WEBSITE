GACHA_ITEMS.forEach(it => {
  it.sellPrice = RARITY_CONFIG[it.rarity].sellPrice;
  it.colorScheme = RARITY_CONFIG[it.rarity];
});

// Calculation verification
export function getRarityStats() {
  const counts: Record<Rarity, number> = {
    common: 0,
    rare: 0,
    epic: 0,
    legend: 0,
    mystic: 0,
  };
  GACHA_ITEMS.forEach(it => {
    counts[it.rarity]++;
  });
  return counts;
}
